#!/usr/bin/env node
// Copies the web app's UI strings (frontend/src/i18n/strings.js) into the phone app, so English and Telugu text
// are written once and the two apps cannot drift apart. Run after editing the web strings:  node scripts/sync_i18n.mjs
import { pathToFileURL } from 'node:url';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const { STRINGS } = await import(pathToFileURL(resolve(root, 'frontend/src/i18n/strings.js')).href);
const out = resolve(root, 'mobile/app/src/i18n/strings.generated.ts');
const body = `// GENERATED by scripts/sync_i18n.mjs from frontend/src/i18n/strings.js. Do not edit by hand.\n` +
  `export const WEB_STRINGS: Record<'en' | 'te', Record<string, string>> = ${JSON.stringify(STRINGS, null, 2)};\n`;
writeFileSync(out, body);
console.log(`wrote ${out}: en ${Object.keys(STRINGS.en).length} keys, te ${Object.keys(STRINGS.te).length} keys`);
