export function deduplicateSources(sourcesList) {
  if (!Array.isArray(sourcesList) || sourcesList.length === 0) return [];
  const unique = [];
  const seenPubs = new Set();
  const seenUrls = new Set();

  for (const s of sourcesList) {
    if (!s) continue;
    const rawPub = s.publisher || '';
    const rawUrl = s.url || '';
    const cPub = getCanonicalPublisher(rawPub, rawUrl);

    let cUrl = rawUrl;
    try {
      const uObj = new URL(rawUrl);
      cUrl = (uObj.origin + uObj.pathname).replace(/\/$/, '').toLowerCase();
    } catch {
      cUrl = rawUrl.split('?')[0].replace(/\/$/, '').toLowerCase();
    }

    if (seenPubs.has(cPub) || (cUrl && seenUrls.has(cUrl))) {
      continue;
    }

    seenPubs.add(cPub);
    if (cUrl) seenUrls.add(cUrl);
    unique.push({
      publisher: cPub,
      url: rawUrl
    });
  }
  return unique;
}

export function isTextTelugu(text) {
  if (!text) return false;
  return /[\u0C00-\u0C7F]/.test(text);
}



// --- AI-Driven Binary Sentiment Classification (Positive / Negative) ---
export function classifyArticleSentiment(art) {
  if (!art) return 'positive';
  // Strictly returns 'positive' or 'negative' from Google GenAI
  return art.sentiment === 'negative' ? 'negative' : 'positive';
}

export function isStatewideArticle(art) {
  if (!art) return false;
  const dist = (art.district_name || '').toLowerCase();
  const c = (art.constituency_name || '').toLowerCase();
  const fullText = `${art.headline || art.title || ''} ${art.summary || ''}`.toLowerCase();

  if (dist === 'statewide' || c === 'statewide' || dist.includes('statewide')) return true;
  if (fullText.includes('రాష్ట్రవ్యాప్తంగా') || fullText.includes('statewide') || fullText.includes('across telangana')) return true;
  if ((!art.constituency_name || art.constituency_name === 'Statewide') && (!art.district_name || art.district_name === 'Statewide')) return true;
  return false;
}



